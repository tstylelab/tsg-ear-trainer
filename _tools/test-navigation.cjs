const assert=require('node:assert/strict');
const {ev,$}=require('./headless.js');
ev('progress=validateProgress({bestRate:{s1:90},lis:{pick:["me1"],melodyScale:"aeo"}});showSelect();chooseCourse("mel");showListen();lisOn=true;lisTimer=setTimeout(()=>{},60000);lisRevealT=setTimeout(()=>{},60000);goHome()');
assert.equal(ev('selectedCourse'),null);
assert.equal($('courseChooser').hidden,false);
assert.equal($('scrListen').hidden,true);
assert.equal(ev('lisOn'),false);
assert.equal(ev('lisTimer'),null);
assert.equal(ev('lisRevealT'),null);
assert.equal(ev('progress.lis.melodyScale'),'aeo');
assert.equal(ev('progress.bestRate.s1'),90);
ev('chooseCourse("mono");enterStage(STAGES.find(s=>s.id==="s1"));phase="q";qi=2;confirm=()=>false;goHome()');
assert.equal($('scrQuiz').hidden,false,'Cancel keeps the current practice');
assert.equal(ev('selectedCourse'),'mono');
assert.equal(ev('qi'),2);
ev('confirm=()=>true;goHome()');
assert.equal($('scrQuiz').hidden,true);
assert.equal($('courseChooser').hidden,false);
assert.equal(ev('phase'),'select');
assert.equal(ev('progress.bestRate.s1'),90);
ev('chooseCourse("chord");showReport();goHome()');
assert.equal($('scrReport').hidden,true);
assert.equal(ev('selectedCourse'),null);
console.log('PASS: home navigation stops playback/timers, clears course selection, preserves settings/scores and honors cancellation');
